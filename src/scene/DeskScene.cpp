DeskScene::DeskScene() = default;
DeskScene::~DeskScene() = default;

const Mesh* DeskScene::makeBox(const Vec3& size, float uvPerMetre)
{
    m_meshes.push_back(prim::box(size, uvPerMetre));
    return m_meshes.back().get();
}

const Texture* DeskScene::texture(const std::string& name) const
{
    auto it = m_textures.find(name);
    return it != m_textures.end() ? it->second.get() : nullptr;
}

void DeskScene::loadTextures()
{
    // All images are generated by tools/generate_textures.py (see CREDITS.md).
    const char* names[] = {"desk_wood", "floor_wood", "wall", "rug", "deskmat", "code", "terminal", "docs", "poster"};
    for (const char* n : names) {
        auto tex = std::make_unique<Texture>();
        tex->loadFromFile(paths::asset(std::string("textures/") + n + ".png"));
        m_textures[n] = std::move(tex);
    }
}

bool DeskScene::init()
{
    loadTextures();

    // Shared unit meshes (uploaded to the GPU once, reused by many nodes).
    m_meshes.push_back(prim::cube());
    m_cube = m_meshes.back().get();
    m_meshes.push_back(prim::quad());
    m_quad = m_meshes.back().get();
    m_meshes.push_back(prim::cylinder(40));
    m_cylinder = m_meshes.back().get();
    m_meshes.push_back(prim::sphere(24, 36));
    m_sphere = m_meshes.back().get();
    m_meshes.push_back(prim::cone(40));
    m_cone = m_meshes.back().get();
    m_meshes.push_back(prim::torus(0.05f, 0.006f, 48, 10));
    m_fanRing = m_meshes.back().get();
    m_meshes.push_back(prim::torus(0.026f, 0.007f, 24, 10));
    m_mugHandle = m_meshes.back().get();

    m_root = std::make_unique<SceneNode>("world");
    buildRoom();
    buildDesk();
    buildDeskItems();
    buildLamp();
    buildChair();
    buildPlant();
    buildPC();

    applyArrangementPreset(settings.arrangement);
    m_monitors.snapTo(settings.arrangement);
    m_env.snap(settings);
    update(0.0f, 0.0f);

    // Count the objects with geometry (printed at start, used in the report).
    std::vector<const SceneNode*> stack{m_root.get()};
    while (!stack.empty()) {
        const SceneNode* n = stack.back();
        stack.pop_back();
        if (n->mesh) ++m_objectCount;
        for (auto& c : n->children) stack.push_back(c.get());
    }
    std::cout << "[Scene] Built " << m_objectCount << " mesh nodes, " << m_keyboard.keyCount() << " keys in one keycap mesh\n";
    return true;
}

void DeskScene::applyArrangementPreset(Arrangement a)
{
    settings.arrangement = a;
    using SC = ScreenContent;
    switch (a) {
    case Arrangement::Single:   settings.content[0] = SC::Code; break;
    case Arrangement::Dual:     settings.content[0] = SC::Code; settings.content[1] = SC::Terminal; break;
    case Arrangement::Triple:   settings.content[0] = SC::Code; settings.content[1] = SC::Docs; settings.content[2] = SC::Terminal; break;
    case Arrangement::Portrait: settings.content[0] = SC::Code; settings.content[1] = SC::Docs; break;
    default: break;
    }
}

void DeskScene::nextArrangement()
{
    int next = (static_cast<int>(settings.arrangement) + 1) % static_cast<int>(Arrangement::Count);
    applyArrangementPreset(static_cast<Arrangement>(next));
}

void DeskScene::update(float dt, float time)
{
    m_time = time;
    m_env.update(dt, settings);
    applySettingsToNodes(dt);

    ScreenTextures tex{texture("code"), texture("terminal"), texture("docs")};
    m_monitors.update(dt, settings, tex);

    m_root->updateWorld();
}

void DeskScene::applySettingsToNodes(float dt)
{
    const SceneSettings& s = settings;

    // Item visibility
    m_plant->visible = s.showPlant;
    m_mug->visible = s.showMug;
    m_pc->visible = s.showPC;
    m_chairRoot->visible = s.showChair;
    m_lampRoot->visible = s.showLamp;
    m_shelf->visible = s.showShelf;
    m_poster->visible = s.showPoster;
    m_rug->visible = s.showRug;

    // Desk lamp hierarchy: each joint only rotates itself, children follow.
    m_lampYaw->rotation.y = s.lampYaw;
    m_lampLower->rotation.x = s.lampLowerArm;
    m_lampUpper->rotation.x = s.lampUpperArm;
    m_lampHead->rotation.x = s.lampHead;
    m_lampBulb->material.albedo = mix(Vec3(0.53f, 0.52f, 0.5f), s.lampColor * 1.5f, m_env.lamp);

    // Ceiling pendant: gentle swing, bulb brightness follows the light level.
    m_pendant->rotation.z = std::sin(m_time * 0.7f) * 1.2f;
    m_ceilingBulb->material.albedo = mix(Vec3(0.48f), Vec3(1.0f, 0.94f, 0.86f) * 1.5f, m_env.ceiling);

    // PC fans spin.
    m_fanAngle += dt * 360.0f;
    m_fanAngle = std::fmod(m_fanAngle, 360.0f);
    for (SceneNode* r : m_fanRotors) r->rotation.z = -m_fanAngle;

    // Chair: user yaw + a spin that slows down with friction.
    m_chairAngle += m_chairSpin * dt;
    m_chairSpin *= std::exp(-1.5f * dt);
    m_chairSwivel->rotation.y = s.chairYaw + m_chairAngle;
}

void DeskScene::collectLights(LightSet& out) const
{
    const SceneSettings& s = settings;
    const Environment& e = m_env;
    out.points.clear();
    out.spots.clear();

    // Ambient light: daylight through the window + light from the ceiling lamp
    // bounced off the walls.
    Vec3 ambient = Vec3(0.30f, 0.31f, 0.33f);
    ambient += Vec3(0.2f, 0.19f, 0.17f) * e.ceiling;
    out.ambient = ambient;

    // Spot 0: desk lamp, follows the lamp head through the hierarchy.
    if (s.showLamp) {
        SpotLight lamp;
        lamp.position = m_lampBulb->worldPosition();
        lamp.direction = -m_lampHead->worldAxis(1);
        lamp.color = s.lampColor;
        lamp.intensity = s.lampIntensity * e.lamp;
        lamp.range = 3.5f;
        lamp.cutoffDeg = 60.0f;
        lamp.exponent = 8.0f;
        out.spots.push_back(lamp);
    }

    // Point 0: ceiling pendant.
    out.points.push_back({m_ceilingBulb->worldPosition() - Vec3(0, 0.05f, 0), {1.0f, 0.94f, 0.86f}, 1.0f * e.ceiling, 7.5f});
    // Point 1: cold light from the main monitor onto the desk and the chair.
    if (m_monitors.isVisible(0) && s.content[0] != ScreenContent::Off) {
        const SceneNode* scr = m_monitors.screen(0);
        Vec3 p = scr->worldPosition() + scr->worldAxis(2) * 0.45f - Vec3(0.0f, 0.3f, 0.0f);
        out.points.push_back({p, Vec3(0.7f, 0.76f, 0.98f) * e.screen, 0.35f, 1.8f});
    }
}
