"""
generate_textures.py - creates every texture in assets/textures procedurally.

No third-party images are used in this project: all textures are generated by
this script (value noise + simple drawing), so there is nothing to license.

Usage (from the project folder):
    pip install numpy pillow
    python tools/generate_textures.py
"""

import os

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "textures")
rng = np.random.default_rng(28)  # fixed seed = same textures every run


# ---------------------------------------------------------------- helpers
def tile_noise(w, h, cx, cy):
    """Smooth value noise that tiles seamlessly (cx x cy random cells, wrapped)."""
    grid = rng.random((cy, cx))
    xs = np.arange(w) / w * cx
    ys = np.arange(h) / h * cy
    x0 = np.floor(xs).astype(int)
    y0 = np.floor(ys).astype(int)
    fx = xs - x0
    fy = ys - y0
    fx = fx * fx * (3 - 2 * fx)
    fy = fy * fy * (3 - 2 * fy)
    x1 = (x0 + 1) % cx
    y1 = (y0 + 1) % cy
    a = grid[np.ix_(y0, x0)]
    b = grid[np.ix_(y0, x1)]
    c = grid[np.ix_(y1, x0)]
    d = grid[np.ix_(y1, x1)]
    top = a + (b - a) * fx[None, :]
    bot = c + (d - c) * fx[None, :]
    return top + (bot - top) * fy[:, None]


def fbm(w, h, cx, cy, octaves=4):
    total = np.zeros((h, w))
    amp, norm = 1.0, 0.0
    for o in range(octaves):
        total += tile_noise(w, h, cx * 2 ** o, cy * 2 ** o) * amp
        norm += amp
        amp *= 0.5
    return total / norm


def hex_rgb(h):
    h = h.lstrip("#")
    return np.array([int(h[i:i + 2], 16) for i in (0, 2, 4)], dtype=float)


def save(arr, name):
    img = Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))
    img.save(os.path.join(OUT, name + ".png"), optimize=True)
    print("wrote", name + ".png", img.size)


def mix(a, b, t):
    return a + (b - a) * t[..., None]


# ---------------------------------------------------------------- materials
def desk_wood():
    w = h = 1024
    warp = fbm(w, h, 2, 6, 3)
    rings = np.sin((np.arange(h)[:, None] / h * 14 + warp * 3.0) * 2 * np.pi) * 0.5 + 0.5
    rings = rings ** 2.2
    streaks = tile_noise(w, h, 6, 220)
    t = np.clip(rings * 0.65 + streaks * 0.35, 0, 1)
    col = mix(hex_rgb("#3e2416"), hex_rgb("#7c5337"), t)
    col *= (0.92 + 0.08 * fbm(w, h, 4, 4, 3))[..., None]
    save(col, "desk_wood")


def floor_wood():
    w = h = 1024
    rows = 8
    rh = h // rows
    img = np.zeros((h, w, 3))
    grain = tile_noise(w, h, 8, 260) * 0.6 + fbm(w, h, 3, 16, 3) * 0.4
    light, dark = hex_rgb("#c39a6b"), hex_rgb("#8a6440")
    for r in range(rows):
        offset = int(rng.integers(0, w))
        plank_len = w // 2
        for p in range(2):
            tint = rng.uniform(0.25, 0.85)
            x0 = (offset + p * plank_len) % w
            xs = (np.arange(plank_len) + x0) % w
            region = grain[r * rh:(r + 1) * rh][:, xs]
            col = mix(dark, light, np.clip(tint + (region - 0.5) * 0.6, 0, 1))
            img[r * rh:(r + 1) * rh, xs] = col
            img[r * rh:(r + 1) * rh, x0:x0 + 2] *= 0.55          # plank end seam
        img[r * rh:r * rh + 2] *= 0.5                            # row seam
    save(img, "floor_wood")


def wall():
    w = h = 512
    n = fbm(w, h, 8, 8, 5)
    v = 232 + (n - 0.5) * 18
    save(np.stack([v, v, v * 0.995], -1), "wall")


def rug():
    w, h = 1024, 744
    img = Image.new("RGB", (w, h), "#e3d6bd")
    d = ImageDraw.Draw(img)
    navy, terra, mustard, cream = "#2b3a55", "#b5603f", "#d4a24c", "#e3d6bd"
    d.rectangle([0, 0, w - 1, h - 1], outline=navy, width=38)
    d.rectangle([52, 52, w - 53, h - 53], outline=terra, width=10)
    step = 92
    for i, cx in enumerate(range(130, w - 100, step)):
        for j, cy in enumerate(range(130, h - 100, step)):
            col = [navy, terra, mustard][(i + j) % 3]
            r = 34
            d.polygon([(cx, cy - r), (cx + r, cy), (cx, cy + r), (cx - r, cy)], fill=col)
            d.polygon([(cx, cy - 12), (cx + 12, cy), (cx, cy + 12), (cx - 12, cy)], fill=cream)
    arr = np.asarray(img).astype(float)
    fibres = tile_noise(w, h, 300, 220) * 0.6 + fbm(w, h, 12, 9, 3) * 0.4
    arr *= (0.86 + 0.18 * fibres)[..., None]
    save(arr, "rug")


def deskmat():
    w, h = 1024, 400
    base = hex_rgb("#1b1c22")
    n = fbm(w, h, 6, 3, 4)
    # Topographic contour lines from the noise field.
    contour = np.abs(np.sin(n * 2 * np.pi * 7)) < 0.06
    img = np.ones((h, w, 3)) * base
    img[contour] = hex_rgb("#2c2f3a")
    img *= (0.93 + 0.1 * tile_noise(w, h, 400, 160))[..., None]   # fabric
    img[:5] = img[-5:] = hex_rgb("#3a3d48")
    img[:, :5] = img[:, -5:] = hex_rgb("#3a3d48")
    save(img, "deskmat")


# ---------------------------------------------------------------- screens
SYNTAX = ["#c678dd", "#61afef", "#98c379", "#d19a66", "#e5c07b", "#abb2bf", "#56b6c2", "#e06c75"]


def code_lines(count, max_indent=4):
    """Fake code structure: blocks with indentation, comments and blank lines."""
    lines, indent = [], 0
    for _ in range(count):
        roll = rng.random()
        if roll < 0.08:
            lines.append(None)                       # blank line
            continue
        kind = "comment" if roll < 0.18 else "code"
        tokens = []
        n = int(rng.integers(2, 7))
        for _ in range(n):
            tokens.append((int(rng.integers(3, 14)), rng.choice(SYNTAX)))
        lines.append((indent, kind, tokens))
        if rng.random() < 0.25 and indent < max_indent:
            indent += 1
        elif rng.random() < 0.3 and indent > 0:
            indent -= 1
    return lines


def screen(name, bg, gutter, lines_count, char_w, line_h, prompt=False):
    w, h = 1024, 576
    s = 2  # supersample for smooth edges
    img = Image.new("RGB", (w * s, h * s), bg)
    d = ImageDraw.Draw(img)
    if gutter:
        d.rectangle([0, 0, 56 * s, h * s], fill=gutter)
    x0 = (72 if gutter else 22) * s
    for i, line in enumerate(code_lines(lines_count)):
        y = (i * line_h + line_h // 2) * s
        if gutter:
            d.rounded_rectangle([18 * s, y - 4 * s, 40 * s, y + 4 * s], 3 * s, fill="#4b4f5c")
        if line is None:
            continue
        indent, kind, tokens = line
        x = x0 + indent * 4 * char_w * s
        if prompt:
            d.rounded_rectangle([x, y - 5 * s, x + char_w * s, y + 5 * s], 2 * s, fill="#4ec94e")
            x += char_w * 2 * s
        for length, color in tokens:
            if kind == "comment":
                color = "#5c6370"
            if prompt:
                color = rng.choice(["#d0d0d0", "#d0d0d0", "#4ec94e", "#e5c07b", "#61afef"])
            x1 = x + length * char_w * s
            if x1 > (w - 20) * s:
                break
            d.rounded_rectangle([x, y - 5 * s, x1, y + 5 * s], 3 * s, fill=color)
            x = x1 + char_w * s
    img = img.resize((w, h), Image.LANCZOS)
    save(np.asarray(img).astype(float), name)


def docs():
    w, h = 576, 1024
    s = 2
    img = Image.new("RGB", (w * s, h * s), "#f4f4f6")
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, w * s, 44 * s], fill="#2a2b31")                        # tab bar
    d.rounded_rectangle([12 * s, 10 * s, 190 * s, 44 * s], 8 * s, fill="#3b3d45")
    d.rectangle([0, 44 * s, w * s, 88 * s], fill="#3b3d45")                   # address bar
    d.rounded_rectangle([16 * s, 54 * s, (w - 16) * s, 78 * s], 12 * s, fill="#26272c")
    d.rectangle([0, 88 * s, w * s, 150 * s], fill="#6d4bd6")                  # site header
    d.rounded_rectangle([28 * s, 108 * s, 220 * s, 130 * s], 6 * s, fill="#f4f4f6")
    y = 180
    for block in range(7):
        d.rounded_rectangle([28 * s, y * s, int(rng.integers(220, 420)) * s, (y + 22) * s], 5 * s, fill="#26272c")
        y += 40
        for _ in range(int(rng.integers(3, 6))):
            d.rounded_rectangle([28 * s, y * s, int(rng.integers(380, 548)) * s, (y + 10) * s], 4 * s, fill="#9a9ca6")
            y += 20
        y += 10
        if block % 2 == 0:
            d.rounded_rectangle([28 * s, y * s, 548 * s, (y + 110) * s], 8 * s, fill="#1f2029")
            yy = y + 18
            for _ in range(5):
                xx = 44
                for _ in range(int(rng.integers(2, 5))):
                    ln = int(rng.integers(30, 90))
                    d.rounded_rectangle([xx * s, yy * s, (xx + ln) * s, (yy + 8) * s], 3 * s, fill=rng.choice(SYNTAX))
                    xx += ln + 10
                yy += 18
            y += 130
        if y > h - 120:
            break
    img = img.resize((w, h), Image.LANCZOS)
    save(np.asarray(img).astype(float), "docs")


def poster():
    w, h = 512, 716
    s = 2
    W, H = w * s, h * s
    yy = np.linspace(0, 1, H)[:, None]
    top, mid, bot = hex_rgb("#140a2e"), hex_rgb("#6a1b6b"), hex_rgb("#ff7a3d")
    t = np.clip(yy / 0.62, 0, 1)
    sky = np.where(t[..., None] < 0.5, mix(top, mid, np.repeat(t * 2, W, 1)), mix(mid, bot, np.repeat(t * 2 - 1, W, 1)))
    img = Image.fromarray(sky.astype(np.uint8))
    d = ImageDraw.Draw(img)
    # Striped sun
    cx, cy, r = W // 2, int(H * 0.50), int(W * 0.30)
    sun = Image.new("L", (W, H), 0)
    ds = ImageDraw.Draw(sun)
    ds.ellipse([cx - r, cy - r, cx + r, cy + r], fill=255)
    for i in range(7):
        y0 = cy + int(r * (0.05 + i * 0.14))
        ds.rectangle([0, y0, W, y0 + 4 * s + i * 2 * s], fill=0)
    sun_col = Image.new("RGB", (W, H), "#ffd25e")
    img.paste(sun_col, (0, 0), sun)
    # Mountains
    pts = [(0, int(H * 0.62))]
    for x in range(0, W + 1, W // 12):
        pts.append((x, int(H * (0.62 - rng.uniform(0.02, 0.11)))))
    pts += [(W, int(H * 0.62)), (W, H), (0, H)]
    d.polygon(pts, fill="#1a0c33")
    # Perspective grid floor
    d.rectangle([0, int(H * 0.62), W, H], fill="#12082a")
    horizon = int(H * 0.62)
    for i in range(-14, 15):
        d.line([(W // 2 + i * 18 * s, horizon), (W // 2 + i * 120 * s, H)], fill="#ff3fb4", width=2 * s)
    for k in range(1, 12):
        y = horizon + int((H - horizon) * (k / 11) ** 2.2)
        d.line([(0, y), (W, y)], fill="#ff3fb4", width=2 * s)
    # "</>" symbol at the top
    c = (W // 2, int(H * 0.17))
    u = 26 * s
    col, lw = "#5ef2ff", 9 * s
    d.line([(c[0] - 2.2 * u, c[1] - u), (c[0] - 3.4 * u, c[1]), (c[0] - 2.2 * u, c[1] + u)], fill=col, width=lw, joint="curve")
    d.line([(c[0] + 2.2 * u, c[1] - u), (c[0] + 3.4 * u, c[1]), (c[0] + 2.2 * u, c[1] + u)], fill=col, width=lw, joint="curve")
    d.line([(c[0] + 0.7 * u, c[1] - 1.3 * u), (c[0] - 0.7 * u, c[1] + 1.3 * u)], fill=col, width=lw)
    img = img.filter(ImageFilter.GaussianBlur(0.6)).resize((w, h), Image.LANCZOS)
    save(np.asarray(img).astype(float), "poster")


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    desk_wood()
    floor_wood()
    wall()
    rug()
    deskmat()
    screen("code", "#1e1f29", "#191a22", 24, 7, 24)
    screen("terminal", "#0b0c0e", None, 24, 7, 24, prompt=True)
    docs()
    poster()
